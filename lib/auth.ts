import { NextAuthOptions } from "next-auth";
import CredentialsProvider from "next-auth/providers/credentials";
import bcrypt from "bcryptjs";
import { prisma } from "./prisma";

export const authOptions: NextAuthOptions = {
  session: { strategy: "jwt" },
  pages: { signIn: "/login" },
  providers: [
    CredentialsProvider({
      name: "Credentials",
      credentials: {
        email: { label: "Email", type: "email" },
        password: { label: "Password", type: "password" },
      },
      async authorize(credentials) {
        if (!credentials?.email || !credentials?.password) return null;
        const email = credentials.email.toLowerCase().trim();

        // The owner account is not a database row — it's a direct check against
        // your own environment variables, so only this one fixed login exists
        // and nobody can register their way into it.
        const ownerEmail = process.env.OWNER_EMAIL?.toLowerCase().trim();
        const ownerPassword = process.env.OWNER_PASSWORD;
        if (ownerEmail && ownerPassword && email === ownerEmail) {
          if (credentials.password === ownerPassword) {
            return { id: "owner", email: ownerEmail, name: ownerEmail, role: "OWNER" };
          }
          return null; // right e-mail, wrong password: don't fall through to customer lookup
        }

        const user = await prisma.user.findUnique({ where: { email } });
        if (!user) return null;
        const valid = await bcrypt.compare(credentials.password, user.passwordHash);
        if (!valid) return null;
        return { id: user.id, email: user.email, name: user.email, role: user.role };
      },
    }),
  ],
  callbacks: {
    async jwt({ token, user }) {
      if (user) {
        token.id = (user as any).id;
        token.role = (user as any).role;
      }
      return token;
    },
    async session({ session, token }) {
      if (session.user) {
        (session.user as any).id = token.id;
        (session.user as any).role = token.role;
      }
      return session;
    },
  },
};
